"""Listing images: deterministic preview pictures built from the product's own Visual QA renders.

Nothing here is generated by AI. Each image shows a real page of the product (rendered by Excel
during Visual QA), plus a short headline and bullets the SEO department wrote and the listing rules
already checked. The example workbook's renders are preferred, so buyers see filled-in pages
instead of empty $0 frames.

Image rules (Etsy guidance for listing photos, researched 2026-10-18):
- 2700 x 2025 px, 4:3 landscape, sRGB, JPEG under 1 MB;
- Etsy crops thumbnails to about 5:4, so every word stays inside a centred 5:4 safe area.

The slots are fixed: "cover", "dashboard", one per sheet render, and "included" (what is in the
download). image_problems() re-opens the saved files and checks them.
"""

from __future__ import annotations

import io
import json
import os
from dataclasses import dataclass
from pathlib import Path, PureWindowsPath

from PIL import Image, ImageChops, ImageDraw, ImageFont

WIDTH, HEIGHT = 2700, 2025
MAX_BYTES = 1_000_000
# A 5:4 crop of a 4:3 image keeps the full height and loses the sides.
SAFE_X = (WIDTH - int(HEIGHT * 5 / 4)) // 2 + 70
SAFE_Y = 70
MAX_SHEET_IMAGES = 4

INK = (24, 38, 44)
MUTED = (84, 102, 110)
PAPER = (247, 245, 240)
TEAL = (31, 78, 90)
ACCENT = (217, 119, 37)
WHITE = (255, 255, 255)

_FONT_CANDIDATES = {
    True: ("C:/Windows/Fonts/segoeuib.ttf", "C:/Windows/Fonts/arialbd.ttf",
           "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
    False: ("C:/Windows/Fonts/segoeui.ttf", "C:/Windows/Fonts/arial.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
}


@dataclass(frozen=True)
class Slot:
    id: str
    source: Path | None  # a sheet PDF render, or None for drawn slides
    sheet: str = ""


def font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    for path in _FONT_CANDIDATES[bold]:
        if os.path.isfile(path):
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size)


def _slug(text: str) -> str:
    return "-".join("".join(c.lower() if c.isalnum() else " " for c in text).split())


def plan_slots(spec: dict, build_dir: Path) -> list[Slot]:
    """Which images this product can have, from its renders. The example workbook is preferred."""
    renders = build_dir / "renders"
    manifest = renders / "manifest.json"
    listed = json.loads(manifest.read_text(encoding="utf-8")).get("sheet_pdfs", []) if manifest.is_file() else []
    # Manifest paths are absolute Windows paths; the files sit next to the manifest.
    local = {name: renders / name for name in (PureWindowsPath(p).name for p in listed)}
    workbooks = [f for f in spec["files"] if f["kind"] == "xlsx"]
    preferred = sorted(workbooks, key=lambda f: not f.get("example_of"))

    def render_for(sheet: str) -> Path | None:
        for workbook in preferred:
            name = f"{_slug(Path(workbook['name']).stem)}--{_slug(sheet)}.pdf"
            if name in local and local[name].is_file():
                return local[name]
        return None

    slots = []
    dashboard = render_for("Dashboard")
    slots.append(Slot("cover", dashboard, "Dashboard"))
    if dashboard is not None:
        slots.append(Slot("dashboard", dashboard, "Dashboard"))
    skip = {"dashboard", "how to use", "lists", "irs rates"}
    sheets = [s["name"] for s in (workbooks[0].get("sheets", []) if workbooks else [])]
    for sheet in sheets:
        if sheet.lower() in skip or len([s for s in slots if s.sheet not in ("Dashboard", "")]) >= MAX_SHEET_IMAGES:
            continue
        if (path := render_for(sheet)) is not None:
            slots.append(Slot(f"sheet:{sheet}", path, sheet))
    slots.append(Slot("included", None))
    return slots


def page_image(pdf: Path, target_width: int) -> Image.Image:
    """First page of a render, trimmed of white margins, at roughly target_width pixels."""
    import pymupdf as fitz

    with fitz.open(pdf) as doc:
        page = doc[0]
        zoom = max(1.0, target_width / page.rect.width * 1.6)
        pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
        image = Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
    box = ImageChops.difference(image, Image.new("RGB", image.size, WHITE)).getbbox()
    if box:
        pad = 24
        image = image.crop((max(box[0] - pad, 0), max(box[1] - pad, 0),
                            min(box[2] + pad, image.width), min(box[3] + pad, image.height)))
    return image


def _wrap(draw: ImageDraw.ImageDraw, text: str, fnt, width: int) -> list[str]:
    lines, line = [], ""
    for word in text.split():
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=fnt) <= width or not line:
            line = trial
        else:
            lines.append(line)
            line = word
    return lines + ([line] if line else [])


def _paste_card(canvas: Image.Image, picture: Image.Image, box: tuple[int, int, int, int]) -> None:
    """Fit a picture inside box on a white card. A tall page is cropped from the top to the box's shape,
    so it fills the width instead of shrinking to a sliver."""
    x0, y0, x1, y1 = box
    inner_w, inner_h = x1 - x0 - 60, y1 - y0 - 60
    if picture.height / picture.width > inner_h / inner_w:
        picture = picture.crop((0, 0, picture.width, int(picture.width * inner_h / inner_w)))
    picture = picture.copy()
    picture.thumbnail((inner_w, inner_h), Image.LANCZOS)
    w, h = picture.size
    cx, cy = x0 + (x1 - x0 - w) // 2, y0 + (y1 - y0 - h) // 2
    draw = ImageDraw.Draw(canvas)
    background = canvas.getpixel((x0, y0))
    shadow = tuple(int(c * 0.82) for c in background)
    draw.rounded_rectangle((cx - 30 + 12, cy - 30 + 16, cx + w + 30 + 12, cy + h + 30 + 16), 28, fill=shadow)
    draw.rounded_rectangle((cx - 30, cy - 30, cx + w + 30, cy + h + 30), 28, fill=WHITE, outline=(220, 220, 214))
    canvas.paste(picture, (cx, cy))


def _text_block(draw, x: int, y: int, width: int, headline: str, bullets: list[str], *, light: bool) -> None:
    head, body = font(118, bold=True), font(64)
    color, muted = (WHITE, (205, 225, 228)) if light else (INK, MUTED)
    for line in _wrap(draw, headline, head, width):
        draw.text((x, y), line, font=head, fill=color)
        y += 140
    y += 40
    for bullet in bullets:
        for i, line in enumerate(_wrap(draw, bullet, body, width - 70)):
            if i == 0:
                draw.ellipse((x, y + 26, x + 26, y + 52), fill=ACCENT)
            draw.text((x + 60, y), line, font=body, fill=muted)
            y += 84
        y += 26


COVER_TEXT_WIDTH = WIDTH - 2 * SAFE_X


def cover_text(draw, headline: str, bullets: list[str]):
    """Fit the cover's headline (at most 2 lines) and bullet line inside the safe area, never past it.

    The headline shrinks until it fits on two lines. The bullets ("a · b · c") shrink to a minimum size,
    then drop the last bullet, then wrap onto two lines. Returns ((font, lines), (font, lines) or None).
    """
    head = None
    for size in range(132, 79, -8):
        f = font(size, bold=True)
        lines = _wrap(draw, headline, f, COVER_TEXT_WIDTH)
        head = (f, lines)
        if len(lines) <= 2 and all(draw.textlength(line, font=f) <= COVER_TEXT_WIDTH for line in lines):
            break
    if not bullets:
        return head, None
    shown = list(bullets[:3])
    while shown:
        joined = "  ·  ".join(shown)
        for size in range(58, 43, -4):
            f = font(size)
            if draw.textlength(joined, font=f) <= COVER_TEXT_WIDTH:
                return head, (f, [joined])
        if len(shown) == 1:
            break
        shown.pop()
    f = font(48)
    return head, (f, _wrap(draw, shown[0] if shown else bullets[0], f, COVER_TEXT_WIDTH)[:2])


def draw_slot(slot: Slot, copy: dict, spec: dict) -> Image.Image:
    headline, bullets = copy.get("headline", ""), copy.get("bullets", [])[:3]
    if slot.id == "cover":
        # Thumbnail-first: a large headline across the top, the filled-in Dashboard below it.
        canvas = Image.new("RGB", (WIDTH, HEIGHT), TEAL)
        draw = ImageDraw.Draw(canvas)
        y = SAFE_Y + 40
        (head, head_lines), sub = cover_text(draw, headline, bullets)
        for line in head_lines:
            draw.text((WIDTH // 2, y), line, font=head, fill=WHITE, anchor="ma")
            y += int(head.size * 1.21)
        if sub:
            sub_font, sub_lines = sub
            for line in sub_lines:
                draw.text((WIDTH // 2, y + 10), line, font=sub_font, fill=(205, 225, 228), anchor="ma")
                y += int(sub_font.size * 1.3)
            y += 34
        if slot.source is not None:
            _paste_card(canvas, page_image(slot.source, 2200), (SAFE_X - 40, y + 20, WIDTH - SAFE_X + 40,
                                                               HEIGHT - SAFE_Y + 20))
        return canvas
    canvas = Image.new("RGB", (WIDTH, HEIGHT), PAPER)
    draw = ImageDraw.Draw(canvas)
    if slot.id == "included":
        _text_block(draw, SAFE_X, SAFE_Y + 120, WIDTH - 2 * SAFE_X, headline, bullets, light=False)
        y = SAFE_Y + 900
        name_font = font(66, bold=True)
        for file_spec in spec["files"][:6]:
            draw.rounded_rectangle((SAFE_X, y, WIDTH - SAFE_X, y + 120), 22, fill=WHITE, outline=(220, 220, 214))
            badge = Path(file_spec["name"]).suffix.upper().lstrip(".")
            draw.rounded_rectangle((SAFE_X + 30, y + 25, SAFE_X + 200, y + 95), 14, fill=TEAL)
            draw.text((SAFE_X + 115, y + 60), badge, font=font(44, bold=True), fill=WHITE, anchor="mm")
            draw.text((SAFE_X + 240, y + 60), file_spec["name"], font=name_font, fill=INK, anchor="lm")
            y += 150
        return canvas
    text_w = 820
    _text_block(draw, SAFE_X, SAFE_Y + 150, text_w, headline, bullets, light=False)
    _paste_card(canvas, page_image(slot.source, 1700),
                (SAFE_X + text_w + 40, SAFE_Y, WIDTH - SAFE_X, HEIGHT - SAFE_Y))
    return canvas


def save_jpeg(image: Image.Image, path: Path) -> Path:
    """Highest JPEG quality that stays under MAX_BYTES."""
    for quality in (90, 85, 80, 75, 70, 60, 50, 40):
        buffer = io.BytesIO()
        image.convert("RGB").save(buffer, "JPEG", quality=quality, optimize=True, progressive=True)
        if buffer.tell() <= MAX_BYTES:
            break
    path.write_bytes(buffer.getvalue())
    return path


def make_images(spec: dict, build_dir: Path, image_copy: dict[str, dict], out_dir: Path) -> list[Path]:
    """Draw every planned slot that has copy. Returns the saved files in listing order."""
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("*.jpg"):
        old.unlink()
    paths = []
    for number, slot in enumerate((s for s in plan_slots(spec, build_dir) if s.id in image_copy), start=1):
        name = f"{number:02d}-{_slug(slot.id.replace('sheet:', ''))}.jpg"
        paths.append(save_jpeg(draw_slot(slot, image_copy[slot.id], spec), out_dir / name))
    return paths


def image_problems(paths: list[Path]) -> list[str]:
    problems = []
    if not paths:
        problems.append("no listing images")
    for path in paths:
        if not path.is_file():
            problems.append(f"{path.name} is missing")
            continue
        with Image.open(path) as image:
            if image.size != (WIDTH, HEIGHT):
                problems.append(f"{path.name} is {image.size[0]}x{image.size[1]}; expected {WIDTH}x{HEIGHT}")
            if image.mode != "RGB":
                problems.append(f"{path.name} is {image.mode}, not RGB")
        if path.stat().st_size > MAX_BYTES:
            problems.append(f"{path.name} is {path.stat().st_size // 1000} KB; keep images under 1 MB")
    return problems
